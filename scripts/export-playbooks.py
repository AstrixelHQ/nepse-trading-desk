#!/usr/bin/env python3
"""Copies the desk playbooks into the StockYan connector, which serves them with get_desk_playbook so that any AI app
using the connector gets the NEPSE Trading Desk method without installing the skill. It also writes index.ts, which
imports every playbook as text: the connector ships as one compiled binary, so the files must be embedded at build
time rather than read from disk.
Usage: python3 scripts/export-playbooks.py <stockyan-backend>/src/mcp/playbooks"""
import pathlib, re, sys

skill = pathlib.Path(__file__).resolve().parent.parent / "skills" / "nepse-trading-desk"
out = pathlib.Path(sys.argv[1]); out.mkdir(parents=True, exist_ok=True)
for old in [*out.glob("*.md"), out / "index.ts"]:
    if old.exists(): old.unlink()
body = re.sub(r"^---\n.*?\n---\n", "", (skill / "SKILL.md").read_text(), flags=re.S)
note = ("> Served by the StockYan connector. Where this text points to a file such as `references/desks/03-analyst-team.md`,\n"
        "> fetch it with `get_desk_playbook(\"03-analyst-team\")` (the file name without folder or `.md`).\n\n")
(out / "overview.md").write_text(note + body.lstrip())
for f in sorted((skill / "references").rglob("*.md")):
    (out / f.name).write_text(f.read_text())
names = sorted(p.stem for p in out.glob("*.md"))
ident = lambda n: "p_" + re.sub(r"\W", "_", n)
lines = ["// Generated by github.com/AstrixelHQ/nepse-trading-desk scripts/export-playbooks.py. Do not edit by hand.",
         "// Text imports embed each playbook in the compiled connector binary."]
lines += [f'import {ident(n)} from "./{n}.md" with {{ type: "text" }};' for n in names]
lines += ["", "export const PLAYBOOKS: Record<string, string> = {"]
lines += [f'  "{n}": {ident(n)},' for n in names]
lines += ["};", ""]
(out / "index.ts").write_text("\n".join(lines))
(out / "md.d.ts").write_text('declare module "*.md" {\n  const text: string;\n  export default text;\n}\n')
print("\n".join(names))
